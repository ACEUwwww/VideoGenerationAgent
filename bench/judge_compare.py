"""Compare judges on the same frames: does a bigger model break the tie?

The 7B judge left four models tied at 4.0 on temporal_consistency and
motion_effects while giving them the same reason verbatim, then separated all
five cleanly when asked to *rank* them instead. That is a capacity limit, not a
missing capability: it can order the videos but cannot resolve them on an
absolute 1-5 scale.

This runs the same prompt, the same strips, and the same call shape against two
models and prints both score sets side by side. Nothing here writes into the
benchmark's caches — a result only replaces the judge after it earns it.
"""

from __future__ import annotations

import base64
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path("/mdata/shiweisong/VideoGenerationAgent")
sys.path.insert(0, str(ROOT))

from bench.config import JudgeConfig, load_config  # noqa: E402
from bench.judge import Judge  # noqa: E402
from bench.frames import build_payload  # noqa: E402

RUN = ROOT / "bench/results/compare"
MODELS = ["cogvideox5b", "wan21_1_3b", "longlive_1_3b", "ours", "openmontage_shot"]


def call(base: str, model: str, system: str, parts: list[dict], max_tokens: int = 1600) -> str:
    body = {
        "model": model,
        "temperature": 0.0,
        "max_tokens": max_tokens,
        "messages": [{"role": "system", "content": system},
                     {"role": "user", "content": parts}],
    }
    req = urllib.request.Request(
        f"{base.rstrip('/')}/chat/completions",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=1800) as resp:
        data = json.loads(resp.read())
    return data["choices"][0]["message"]["content"]


def dynamic_parts(grids: dict[str, list[str]], dimension: str, grid_size: int) -> list[dict]:
    """The bench's own dynamic-message layout, so the comparison is like for like.

    ``grid_size`` must be the frames per strip, not the number of strips. The
    first version of this function derived it from ``len(grids[model])``, which
    is 1 at grid_size=8, so the prompt claimed "1 key frame per second in a 1*1
    grid view" over an 8-frame strip. That misdescription by itself moved
    motion_effects from 2/4/4/4/4 to 1/3/4/5/1 — which is why the harness has to
    reproduce the bench prompt exactly before any model comparison means
    anything.
    """
    label = {"temporal_consistency": "temporal consistency", "motion_effects": "motion effects"}[dimension]
    parts: list[dict] = [{"type": "text", "text": (
        "The following images are concatenated by the key frames of the video."
        f"And one of the following images arranges {grid_size} key frames per second from a video "
        f"in a 1*{grid_size} grid view.\n"
    )}]
    parts.append({"type": "text", "text": "Please associate the images in time order to help you watch the whole video.\n"})
    for name in MODELS:
        parts.append({"type": "text", "text": f"\nFrames from the video generated by {name}:\n"})
        for strip in grids[name]:
            parts.append({"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{strip}", "detail": "low"}})
    parts.append({"type": "text", "text": f"Find the issues of the video in {label} and then evaluate the {label} of the video.\n"})
    parts.append({"type": "text", "text": (
        "Provide your analysis, then end with one line per video in exactly this format:\nFinal Scores:\n"
        + "".join(f"- {name}: <integer 1-5> ,because ...\n" for name in MODELS)
    )})
    return parts


def parse_scores(text: str) -> dict[str, int | None]:
    """Per-model scores, tolerating the markdown a larger model writes.

    The 7B echoes the requested line literally (``- ours: 4 ,because``). The
    32B wraps the label in bold (``- **ours**: 4 , because``) and inserts a
    space after the comma. The bench's own parser found nothing at all for the
    32B replies — four 5s and two 4s read back as five Nones — so the label is
    matched with optional emphasis markers around it.
    """
    out: dict[str, int | None] = {}
    for name in MODELS:
        m = re.search(
            rf"(?<![A-Za-z0-9_])[\*_]*{re.escape(name)}[\*_]*(?![A-Za-z0-9_])\s*\**\s*[:\-]\s*\**\s*(\d{{1,2}})",
            text, re.I,
        )
        out[name] = int(m.group(1)) if m else None
    return out


def jaccard(a: str, b: str) -> float:
    """Share of words two reasons have in common.

    Identical reasons across models are the signature of a judge that stopped
    discriminating; measuring it is less arguable than reading the replies.
    """
    wa, wb = set(a.lower().split()), set(b.lower().split())
    return len(wa & wb) / len(wa | wb) if (wa | wb) else 1.0


def main(argv: list[str]) -> int:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="http://127.0.0.1:8790/v1")
    ap.add_argument("--model", default="qwen2.5-vl-7b-local")
    ap.add_argument("--grid-size", type=int, default=8)
    ap.add_argument("--dimensions", nargs="+",
                    default=["temporal_consistency", "motion_effects", "imaging_quality"])
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args(argv[1:])

    cfg = load_config()
    jc = JudgeConfig(**{**cfg.judge.__dict__, "grid_size": args.grid_size})
    grids = {
        m: build_payload(RUN / "videos" / m / f"{m}_0.mp4", jc).grid_frames
        for m in MODELS
    }
    print(f"judge={args.model} @ {args.base}  grid_size={args.grid_size}  "
          f"images/call={sum(len(g) for g in grids.values())}", flush=True)

    results: dict[str, dict] = {}
    for dimension in args.dimensions:
        # imaging_quality is a static dimension upstream: one call per model,
        # no cross-model comparison. Scoring it with the dynamic layout would
        # be a different question, so it is skipped rather than approximated.
        if dimension == "imaging_quality":
            continue
        print(f"\n=== {dimension}", flush=True)
        # The bench's own system prompt, character for character. A shortened
        # prompt moves the scores: motion_effects went 1/3/4/5/1 under a
        # one-line system message and 1/5/4/5/1 under Video-Bench's 5.8KB
        # one, on identical images. Comparing judges requires the same
        # question, not just the same frames.
        system = Judge(load_config().judge).prompts[dimension]
        text = call(args.base, args.model, system, dynamic_parts(grids, dimension, args.grid_size))
        scores = parse_scores(text)
        tail = text[-700:]
        reasons = {}
        for name in MODELS:
            m = re.search(rf"- {re.escape(name)}\s*:\s*\d{{1,2}}\s*,?\s*because\s*(.*)", tail, re.S | re.I)
            reasons[name] = (m.group(1).strip() if m else "")
        vals = [v for v in scores.values() if v is not None]
        pairs = [
            jaccard(reasons[a], reasons[b])
            for i, a in enumerate(MODELS) for b in MODELS[i + 1:]
            if reasons[a] and reasons[b]
        ]
        results[dimension] = {
            "scores": scores,
            "distinct": len(set(vals)),
            "spread": (max(vals) - min(vals)) if vals else 0,
            "reason_jaccard_max": round(max(pairs), 3) if pairs else None,
            "raw": text,
        }
        print(f"  scores      {scores}")
        print(f"  distinct={results[dimension]['distinct']}/5  spread={results[dimension]['spread']}  "
              f"max_reason_overlap={results[dimension]['reason_jaccard_max']}")
        print(f"  tails:")
        for name in MODELS:
            print(f"    {name:17} {reasons[name][:110]!r}")

    if args.out:
        args.out.write_text(json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"\nwritten {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
